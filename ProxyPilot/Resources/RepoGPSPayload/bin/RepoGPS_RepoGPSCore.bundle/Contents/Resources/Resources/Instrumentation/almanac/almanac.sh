#!/bin/sh
# Repo Forensics 101 — Almanac composer
# Runs units 01–05 against a repo and emits the full single-page almanac on
# stdout. Deterministic: every line derives from git history at HEAD — no
# wall-clock timestamps, no network, no synthesis. Same HEAD → same bytes.
# Usage: almanac.sh [repo-path] > docs/ALMANAC.md
set -e
# Pin the C locale for the whole generator.
#
# MEASURED, and the reason this exists: awk's printf "%.2f" uses the LOCALE
# decimal separator, so a de_DE machine emits "2,28 commits/day" where a C
# machine emits "2.28" — 74 differing lines on a 405-commit repo. Determinism is
# a stated property of this page, and a check that generates twice on ONE machine
# structurally cannot observe this. The check that found it varied the
# environment instead of repeating the input.
#
# ALSO COVERED, belt-and-braces: sort collation decides the order of tags sharing
# a timestamp (03-eras.sh sets LC_ALL=C on that sort explicitly too), and POSIX
# leaves tolower() locale-dependent, which would matter to 04-breakage.sh's
# ASCII fix-pattern. Note that macOS awk (BWK, 20200816) was tested and its
# tolower() is ASCII-only regardless of locale — `LC_ALL=tr_TR.UTF-8 awk
# 'BEGIN{print tolower("FIX")}'` prints "fix". So the tolower hazard is a
# portability guard against other awks, NOT an observed failure here. Do not
# repeat it as a measured fact.
export LC_ALL=C
bindir=$(cd "$(dirname "$0")" && pwd)
repo="${1:-.}"
repo=$(cd "$repo" && pwd)
cd "$repo"
git rev-parse HEAD >/dev/null 2>&1 || { echo "almanac: no commits in $repo" >&2; exit 1; }

# Per-repo config, sourced once here and exported so every unit inherits it.
# Units source it themselves too, so they behave identically when run standalone.
# Sourcing is idempotent: config.sh assigns only when a variable is unset.
_cfg="$repo/scripts/almanac/config.sh"
if [ -r "$_cfg" ]; then
  . "$_cfg"
  export ALMANAC_FIX_PATTERN ALMANAC_FIX_WINDOW_DAYS
fi

name=$(basename "$(git rev-parse --show-toplevel)")
head_short=$(git rev-parse --short HEAD)
head_date=$(git log -1 --format=%cs)
branch=$(git rev-parse --abbrev-ref HEAD)

cat <<EOF
# Almanac — $name

_Programmatic history through commit \`$head_short\` on \`$branch\` ($head_date). Generated by
Repo Forensics 101 \`almanac.sh\`; regenerated by the commit gate — do not hand-edit.
Every number is derived from git history at the anchor commit: deterministic, offline,
no synthesis. When committed by the gate, this file describes history through the
commit's PARENT — the commit carrying it cannot count itself. That one-commit lag is
structural, not staleness._

EOF

for unit in 01-genesis 02-cadence 03-eras 04-breakage 05-churn; do
  "$bindir/$unit.sh" "$repo"
  echo
done
